set local role anon;
select throws_ok($$ select public.submit_ranking('Imposter',(select rankings from fixture)) $$,'42501',null,'Unauthenticated callers cannot submit');
select throws_ok($$ insert into public.submissions(user_id,username,rankings) values('00000000-0000-0000-0000-000000000101','Imposter',(select rankings from fixture)) $$,'42501',null,'Direct anonymous insert denied');
reset role;
select set_config('request.jwt.claims','{"sub":"00000000-0000-0000-0000-000000000101","role":"authenticated"}',true);
set local role authenticated;
select lives_ok($$ select public.submit_ranking('Alice',(select rankings from fixture)) $$,'Anonymous identity can submit');
