select ok(public.valid_tube_rankings((select rankings from fixture)), 'Complete rankings accepted');
select is(public.valid_tube_rankings('{}'::jsonb),false,'Empty ranking rejected');
select is(public.valid_tube_rankings((select rankings - 'central' from fixture)),false,'Missing line rejected');
select is(public.valid_tube_rankings((select rankings || '{"central":"S"}'::jsonb from fixture)),false,'Unknown tier rejected');
select is(public.valid_tube_rankings((select rankings || '{"fake":"A*"}'::jsonb from fixture)),false,'Extra line rejected');
